"""
Regenerate the frontend's hardcodedRelations.ts from the live graph.

    python scripts/export_relations.py --out ../frontend/src/lib/hardcodedRelations.ts
    python scripts/export_relations.py --out ... --allow-empty   # write even if a domain has no edges

Why a generated snapshot: the globe draws these lines instantly (and when the
backend is asleep on a free host) instead of waiting on Neo4j. Generating
them from the graph keeps every line traceable to a relationship in Neo4j;
hand-typed weights are not.

Refuses to write when a domain returns no edges (e.g. economy not loaded
yet), so a half-built graph cannot wipe the existing file. Run it after
scripts/rebuild_graph.py has completed.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
os.chdir(ROOT)
sys.path.insert(0, str(ROOT))

from common.db import Neo4jConnection  # noqa: E402

W = "coalesce(r.normalized_weight, r.score, r.weight, r.similarity, r.value)"

# domain -> (description, cypher). Each query returns src, dst, w.
# Year-scoped relationships are filtered to their latest year.
QUERIES: dict[str, tuple[str, str]] = {
    "overview": (
        "IS_INFLUENTIAL_TO (all domains)",
        f"""MATCH (a:Country)-[r:IS_INFLUENTIAL_TO]->(b:Country)
            WITH a, b, max({W}) AS w WHERE w IS NOT NULL
            RETURN a.name AS src, b.name AS dst, w ORDER BY w DESC LIMIT $limit""",
    ),
    "defence": (
        "IS_INFLUENTIAL_TO where domain = defense (arms-export influence)",
        f"""MATCH (a:Country)-[r:IS_INFLUENTIAL_TO]->(b:Country)
            WHERE toLower(coalesce(r.domain, '')) STARTS WITH 'defen'
            WITH a, b, max({W}) AS w WHERE w IS NOT NULL
            RETURN a.name AS src, b.name AS dst, w ORDER BY w DESC LIMIT $limit""",
    ),
    "economy": (
        "HAS_TRADE_VOLUME_WITH, latest year",
        f"""MATCH ()-[r0:HAS_TRADE_VOLUME_WITH]->() WITH max(r0.year) AS latest
            MATCH (a:Country)-[r:HAS_TRADE_VOLUME_WITH]->(b:Country) WHERE r.year = latest
            WITH a, b, {W} AS w WHERE w IS NOT NULL
            RETURN a.name AS src, b.name AS dst, w ORDER BY w DESC LIMIT $limit""",
    ),
    "geopolitics": (
        "ALIGNED_WITH (UNGA vote similarity / diplomatic alignment)",
        f"""MATCH (a:Country)-[r:ALIGNED_WITH]->(b:Country)
            WITH a, b, max({W}) AS w WHERE w IS NOT NULL
            RETURN a.name AS src, b.name AS dst, w ORDER BY w DESC LIMIT $limit""",
    ),
    "climate": (
        "INCREASES_CONFLICT_RISK (climate → conflict bridge)",
        f"""MATCH (a:Country)-[r:INCREASES_CONFLICT_RISK]->(b:Country)
            WITH a, b, max({W}) AS w WHERE w IS NOT NULL
            RETURN a.name AS src, b.name AS dst, w ORDER BY w DESC LIMIT $limit""",
    ),
}


def fetch(conn: Neo4jConnection, limit: int) -> dict[str, list[dict]]:
    out: dict[str, list[dict]] = {}
    for domain, (_, q) in QUERIES.items():
        rows = conn.run_query(q, {"limit": limit})
        ws = [float(r["w"]) for r in rows]
        lo, hi = (min(ws), max(ws)) if ws else (0.0, 1.0)
        span = (hi - lo) or 1.0
        out[domain] = [
            {
                "fromCountry": r["src"],
                "toCountry": r["dst"],
                # Min-max scaled to 0.15..1 so the weakest drawn line is still visible.
                "weight": round(0.15 + 0.85 * (float(r["w"]) - lo) / span, 4),
                "domain": domain,
            }
            for r in rows
            if r["src"] and r["dst"] and r["src"] != r["dst"]
        ]
    return out


def render(data: dict[str, list[dict]], counts: dict[str, int]) -> str:
    stamp = dt.datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [
        "// AUTO-GENERATED by backend/scripts/export_relations.py — do not edit manually.",
        f"// Generated {stamp} from the Neo4j graph. Re-run after rebuilding the graph.",
        "// Sources per domain:",
    ]
    for d, (desc, _) in QUERIES.items():
        lines.append(f"//   {d:<12} {desc}: {counts.get(d, 0)} edges")
    lines += [
        "",
        "export type RelationDomain =",
        '  | "overview"',
        '  | "defence"',
        '  | "economy"',
        '  | "geopolitics"',
        '  | "climate"',
        '  | "simulator";',
        "",
        "export interface HardcodedRelation {",
        "  fromCountry: string;",
        "  toCountry: string;",
        "  weight: number;",
        "  domain: RelationDomain;",
        "}",
        "",
        "export const HARDCODED_RELATIONS: Record<RelationDomain, HardcodedRelation[]> = {",
    ]
    for d in ("overview", "defence", "economy", "geopolitics", "climate"):
        lines.append(f"  {d}: [")
        for rel in data.get(d, []):
            lines.append(
                f"    {{ fromCountry: {json.dumps(rel['fromCountry'], ensure_ascii=False)}, "
                f"toCountry: {json.dumps(rel['toCountry'], ensure_ascii=False)}, "
                f"weight: {rel['weight']}, domain: \"{d}\" }},"
            )
        lines.append("  ],")
    lines.append("  simulator: [],")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True, help="path to frontend/src/lib/hardcodedRelations.ts")
    ap.add_argument("--limit", type=int, default=200, help="max edges per domain")
    ap.add_argument("--allow-empty", action="store_true", help="write even if some domains have no edges")
    args = ap.parse_args()

    data = fetch(Neo4jConnection(), args.limit)
    counts = {d: len(v) for d, v in data.items()}
    for d, n in counts.items():
        print(f"  {d:<12} {n:>4} edges")
    empty = [d for d, n in counts.items() if n == 0]
    if empty and not args.allow_empty:
        print(f"\nNot writing: no edges for {', '.join(empty)}. Load that data first, "
              f"or pass --allow-empty to write anyway.")
        return 1

    out = Path(args.out)
    out.write_text(render(data, counts), encoding="utf-8")
    print(f"\nWrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
